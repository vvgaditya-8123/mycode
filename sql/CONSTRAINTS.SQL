 CREATE TABLE COURSES (
     COURSE_ID VARCHAR2(10) PRIMARY KEY,
      COURSE_NAME VARCHAR2(50) NOT NULL UNIQUE
       );
       CREATE TABLE STUDENTS ( 
        ID VARCHAR2(10) PRIMARY KEY,
        NAME VARCHAR2(50)      NOT NULL,
         AGE NUMBER(2)              CHECK(AGE BETWEEN 18 AND 99),
          DOA DATE                         DEFAULT SYSDATE,
           COURSE_ID VARCHAR2(10) REFERENCES COURSES(COURSE_ID),
            MOB_NO NUMBER(10)     UNIQUE CHECK(LENGTH(MOB_NO)=10),
             MAIL_ID VARCHAR2(50)     UNIQUE, 
             CITY VARCHAR2(10) 
       );
